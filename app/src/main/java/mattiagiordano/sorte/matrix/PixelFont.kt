package mattiagiordano.sorte.matrix

/**
 * Font a pixel disegnati a mano. Ogni glifo è una lista di righe ('#' = acceso).
 * I glifi più alti del font (es. Ì con l'accento) sporgono verso l'alto: il testo è allineato in basso.
 */
class PixelFont(val height: Int, private val glyphs: Map<Char, List<String>>) {

    fun width(text: String): Int =
        text.sumOf { glyph(it)[0].length } + (text.length - 1).coerceAtLeast(0)

    /** Disegna [text] centrato orizzontalmente, con la riga di base (ultima riga dei glifi) a [bottom]. */
    fun drawCentered(frame: Frame, text: String, bottom: Int, brightness: Int = Frame.FULL) {
        draw(frame, text, (Frame.N - width(text)) / 2, bottom, brightness)
    }

    fun draw(frame: Frame, text: String, left: Int, bottom: Int, brightness: Int = Frame.FULL) {
        var x = left
        for (c in text) {
            val g = glyph(c)
            val top = bottom - g.size + 1
            g.forEachIndexed { row, line ->
                line.forEachIndexed { col, ch -> if (ch == '#') frame[x + col, top + row] = brightness }
            }
            x += g[0].length + 1
        }
    }

    private fun glyph(c: Char) = glyphs[c] ?: glyphs.getValue(' ')

    companion object {
        private fun g(vararg rows: String) = rows.toList()

        /** 5×7 per le parole principali e i numeri. */
        val BIG = PixelFont(7, mapOf(
            ' ' to g("...", "...", "...", "...", "...", "...", "..."),
            '0' to g(".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###."),
            '1' to g("..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###."),
            '2' to g(".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####"),
            '3' to g("#####", "...#.", "..#..", "...#.", "....#", "#...#", ".###."),
            '4' to g("...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#."),
            '5' to g("#####", "#....", "####.", "....#", "....#", "#...#", ".###."),
            '6' to g("..##.", ".#...", "#....", "####.", "#...#", "#...#", ".###."),
            '7' to g("#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#..."),
            '8' to g(".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###."),
            '9' to g(".###.", "#...#", "#...#", ".####", "....#", "...#.", ".##.."),
            'A' to g(".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"),
            'H' to g("#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"),
            'M' to g("#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"),
            'D' to g("####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."),
            'E' to g("#####", "#....", "#....", "####.", "#....", "#....", "#####"),
            'I' to g(".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."),
            'Ì' to g(".#...", "..#..", ".....", ".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."),
            'N' to g("#...#", "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#"),
            'O' to g(".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."),
            'S' to g(".###.", "#...#", "#....", ".###.", "....#", "#...#", ".###."),
            'Y' to g("#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.."),
            '?' to g(".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#.."),
        ))

        /** 3×5 per le parole secondarie ("ma…", "forse") e l'etichetta del dado. */
        val SMALL = PixelFont(5, mapOf(
            ' ' to g("..", "..", "..", "..", ".."),
            '.' to g(".", ".", ".", ".", "#"),
            '0' to g("###", "#.#", "#.#", "#.#", "###"),
            '1' to g(".#.", "##.", ".#.", ".#.", "###"),
            '2' to g("##.", "..#", ".#.", "#..", "###"),
            '3' to g("##.", "..#", ".#.", "..#", "##."),
            '4' to g("#.#", "#.#", "###", "..#", "..#"),
            '5' to g("###", "#..", "##.", "..#", "##."),
            '6' to g(".##", "#..", "###", "#.#", "###"),
            '7' to g("###", "..#", ".#.", ".#.", ".#."),
            '8' to g("###", "#.#", "###", "#.#", "###"),
            '9' to g("###", "#.#", "###", "..#", "##."),
            'A' to g(".#.", "#.#", "###", "#.#", "#.#"),
            'B' to g("##.", "#.#", "##.", "#.#", "##."),
            'D' to g("##.", "#.#", "#.#", "#.#", "##."),
            'E' to g("###", "#..", "##.", "#..", "###"),
            'F' to g("###", "#..", "##.", "#..", "#.."),
            'M' to g("#...#", "##.##", "#.#.#", "#...#", "#...#"),
            'N' to g("#..#", "##.#", "#.##", "#..#", "#..#"),
            'O' to g(".#.", "#.#", "#.#", "#.#", ".#."),
            'R' to g("##.", "#.#", "##.", "#.#", "#.#"),
            'S' to g(".##", "#..", ".#.", "..#", "##."),
            'T' to g("###", ".#.", ".#.", ".#.", ".#."),
            'U' to g("#.#", "#.#", "#.#", "#.#", "###"),
            'Y' to g("#.#", "#.#", ".#.", ".#.", ".#."),
        ))
    }
}
